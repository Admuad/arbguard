// Writes apps/web/.env.local from the latest AnvilDemo broadcast.
//
// Reads contracts/broadcast/AnvilDemo.s.sol/31337/run-latest.json and maps
// the deployed contracts by name to the NEXT_PUBLIC_* env vars (see
// apps/web/.env.example for the shared contract).
//
// Disambiguation:
// - GuardedPool is deployed twice: the GUARDED pool's constructor arg
//   [2] (arbGuard) is the ArbGuard address, the UNGUARDED pool's is the
//   zero address. Falls back to deploy order (guarded first) if the args
//   are absent from the broadcast JSON.
// - MockERC20 is deployed twice: mWETH first, mUSDC second (creation
//   order in AnvilDemo.s.sol).
// - NEXT_PUBLIC_DEPLOY_BLOCK is the lowest block number in the broadcast
//   receipts (the deploy block), so the feed scans from deployment.
//
// Run (after starting anvil + running the demo broadcast):
//   cd apps/web && node scripts/write-local-env.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webDir = join(here, "..");
const repoDir = join(webDir, "..", "..");
const broadcastPath = join(
  repoDir,
  "contracts",
  "broadcast",
  "AnvilDemo.s.sol",
  "31337",
  "run-latest.json",
);

const ZERO = "0x0000000000000000000000000000000000000000";

let broadcast;
try {
  broadcast = JSON.parse(readFileSync(broadcastPath, "utf8"));
} catch (err) {
  console.error(`Could not read broadcast file: ${broadcastPath}`);
  console.error("Run the Anvil demo broadcast first (see apps/web/LOCAL-DEMO.md).");
  process.exit(1);
}

const txs = (broadcast.transactions ?? []).filter((t) => t.transactionType === "CREATE");
const byName = (name) => txs.filter((t) => t.contractName === name);
const addr = (t) => t.contractAddress;

function first(name) {
  const list = byName(name);
  if (list.length === 0) throw new Error(`No ${name} deployment found in ${broadcastPath}`);
  return addr(list[0]);
}

// GuardedPool x2: constructor args are [token0, token1, arbGuard].
// Guarded => arbGuard != zero; unguarded => arbGuard == zero.
// Fall back to deploy order (guarded first in AnvilDemo.s.sol).
const pools = byName("GuardedPool");
if (pools.length < 2) throw new Error(`Expected 2 GuardedPool deployments, found ${pools.length}`);
let guardedPool;
let unguardedPool;
const withArgs = pools.filter((t) => Array.isArray(t.arguments) && t.arguments.length >= 3);
if (withArgs.length === 2) {
  guardedPool = addr(withArgs.find((t) => t.arguments[2].toLowerCase() !== ZERO.toLowerCase()));
  unguardedPool = addr(withArgs.find((t) => t.arguments[2].toLowerCase() === ZERO.toLowerCase()));
} else {
  guardedPool = addr(pools[0]);
  unguardedPool = addr(pools[1]);
}

// MockERC20 x2: mWETH is created first, mUSDC second (AnvilDemo.s.sol order).
const tokens = byName("MockERC20");
if (tokens.length < 2) throw new Error(`Expected 2 MockERC20 deployments, found ${tokens.length}`);
const mweth = addr(tokens[0]);
const musdc = addr(tokens[1]);

// Deploy block: lowest block number across the broadcast receipts.
const receipts = broadcast.receipts ?? [];
let deployBlock = null;
for (const r of receipts) {
  const n = typeof r.blockNumber === "string" ? parseInt(r.blockNumber, 16) : Number(r.blockNumber);
  if (Number.isFinite(n) && (deployBlock === null || n < deployBlock)) deployBlock = n;
}
if (deployBlock === null) deployBlock = 1;

const env = `# ArbGuard local Anvil demo — generated by apps/web/scripts/write-local-env.mjs
# from contracts/broadcast/AnvilDemo.s.sol/31337/run-latest.json.
# Do NOT commit. Re-run the script after every fresh AnvilDemo broadcast.
# WalletConnect project ID: leave blank for build-only, or set a free one
# from https://cloud.walletconnect.com to connect a wallet.
NEXT_PUBLIC_WALLETCONNECT_PROJECT_ID=
NEXT_PUBLIC_CHAIN_ID=31337
NEXT_PUBLIC_RPC_URL=http://127.0.0.1:8545
NEXT_PUBLIC_ARB_GUARD_ADDRESS=${first("ArbGuard")}
NEXT_PUBLIC_GUARDED_VAULT_ADDRESS=${first("GuardedVault")}
NEXT_PUBLIC_UNGUARDED_VAULT_ADDRESS=${first("UnguardedVault")}
NEXT_PUBLIC_GUARDED_POOL_ADDRESS=${guardedPool}
NEXT_PUBLIC_UNGUARDED_POOL_ADDRESS=${unguardedPool}
NEXT_PUBLIC_ATTACKER_ADDRESS=${first("Attacker")}
NEXT_PUBLIC_MWETH_ADDRESS=${mweth}
NEXT_PUBLIC_MUSDC_ADDRESS=${musdc}
NEXT_PUBLIC_DEPLOY_BLOCK=${deployBlock}
`;

writeFileSync(join(webDir, ".env.local"), env);
console.log("Wrote apps/web/.env.local");
for (const line of env.split("\n")) {
  if (line.startsWith("NEXT_PUBLIC_") && !line.includes("WALLETCONNECT")) console.log(`  ${line}`);
}
